"""Reproduce private wx3.2.12 dialog adapters from hash-pinned upstream sources.

wxGTK/MSW need not build/install wxGenericFileDialog/wxGenericDirDialog. Keep
the generic wx GUI implementation, not an unsafe platform-native fallback.
Generated sources are checked in; building the bridge requires no Python/network.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCES = {
    "src/generic/filedlgg.cpp": "30516b3e071b920e370c46e4930ebb251f984fe1400361c7fe38c387c268ecc9",
    "include/wx/generic/filedlgg.h": "bf4d6edda285f6fbc8ae6349b234be9e4aefdf61542cebcff6be602da79aa568",
    "src/generic/dirdlgg.cpp": "9ffe55554293063628e2dc5d178b6d4c658f3cb34f50793cf437a281f96cf6b6",
    "include/wx/generic/dirdlgg.h": "d5c485b9592ad0c61ad5ac7d87400f0ef3a55ddf90d900e6e2198174870a582f",
}


def adapt(name, source):
    source = source.replace("wxGenericFileDialog", "WxlGenericFileDialog")
    source = source.replace("wxGenericDirDialog", "WxlGenericDirDialog")
    for kind in ("FILE", "DIR"):
        source = source.replace(f"_WX_{kind}DLGG_H_", f"WXL_PRIVATE_{kind}DLGG_H")
    source = source.replace('"wx/generic/filedlgg.h"', '"filedlgg.h"')
    source = source.replace('"wx/generic/dirdlgg.h"', '"dirdlgg.h"')
    source = re.sub(r"WXDLLIMPEXP_(?:FWD_)?CORE (WxlGeneric(?:File|Dir)Dialog)", r"\1", source)
    # The wxFileDialog native proxy belongs to wx itself, never our private copy.
    source = re.sub(r"#ifdef wxHAS_GENERIC_FILEDIALOG\n.*?#endif // wxHAS_GENERIC_FILEDIALOG",
                    "// Native wxFileDialog proxy intentionally omitted.", source, flags=re.S)
    if name.endswith("dirdlgg.h"):
        source = '#include <wx/dirdlg.h>\n' + source
    return "// wxLambda private adapter; generated by tools/generic_dialogs.py.\n" + source


def generate(upstream):
    outputs = {}
    for name, digest in SOURCES.items():
        raw = (upstream / name).read_bytes().replace(b"\r\n", b"\n")
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f"Pinned wx3.2.12 source hash mismatch: {name}")
        outputs[ROOT / "native/generic-dialogs" / Path(name).name] = adapt(name, raw.decode())
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        for path, source in generate(args.upstream).items():
            if args.check:
                if path.read_text() != source:
                    raise ValueError(f"Stale private adapter: {path.name}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(source)
        print("PASS: four hash-pinned private generic dialog adapters")
    except (OSError, ValueError) as error:
        parser.exit(1, f"Generic dialog generation rejected: {error}\n")


if __name__ == "__main__":
    main()
